import type { Language, ProductCategory } from './types.ts';

export function formatUZS(amount: number, lang: Language = 'uz'): string {
  const formatted = Math.round(amount)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  return lang === 'uz' ? `${formatted} so'm` : `${formatted} UZS`;
}

export function formatNumber(num: number): string {
  return Math.round(num)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

export function getCategoryLabel(cat: ProductCategory | 'All', lang: Language): string {
  if (cat === 'All') return lang === 'uz' ? 'Barchasi' : 'All Categories';
  const map: Record<ProductCategory, { uz: string; en: string }> = {
    'Ustki kiyim': { uz: 'Ustki kiyim', en: 'Apparel' },
    'Oyoq kiyim': { uz: 'Oyoq kiyim', en: 'Footwear' },
    'Aksessuarlar': { uz: 'Aksessuarlar', en: 'Accessories' },
  };
  return map[cat][lang];
}

